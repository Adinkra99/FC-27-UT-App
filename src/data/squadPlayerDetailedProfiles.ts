/**
 * Helper to retrieve a full detailed player profile by id or player name
 */
export function getDetailedPlayerProfile(
  idOrName: string
): FullPlayerProfile | null {
  if (!idOrName) return null;

  // Direct ID match
  if (SQUAD_PLAYER_DETAILED_PROFILES[idOrName]) {
    return SQUAD_PLAYER_DETAILED_PROFILES[idOrName];
  }

  const query = idOrName.toLowerCase().trim();

  // Search by name or knownAs
  for (const profile of Object.values(SQUAD_PLAYER_DETAILED_PROFILES)) {
    if (
      profile.bio.fullName.toLowerCase() === query ||
      profile.bio.knownAs?.toLowerCase() === query ||
      profile.bio.fullName.toLowerCase().includes(query) ||
      query.includes(profile.bio.knownAs?.toLowerCase() || '___')
    ) {
      return profile;
    }
  }

  return null;
}
