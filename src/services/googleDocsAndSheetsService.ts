/**
 * Lists Google Docs files in the user's Google Drive.
 */
export async function listGoogleDocs(): Promise<GoogleDocItem[]> {
  const token = getValidToken();
  const query = encodeURIComponent("mimeType = 'application/vnd.google-apps.document' and trashed = false");
  const res = await fetch(
    `https://www.googleapis.com/drive/v3/files?q=${query}&fields=files(id,name,modifiedTime,webViewLink)&orderBy=modifiedTime desc&pageSize=15`,
    {
      headers: { Authorization: `Bearer ${token}` },
    }
  );

  if (!res.ok) {
    const errText = await res.text();
    throw new Error(`Failed to list Google Docs (${res.status}): ${errText}`);
  }

  const data = await res.json();
  return (data.files || []).map((f: any) => ({
    id: f.id,
    name: f.name,
    modifiedTime: f.modifiedTime,
    webViewLink: f.webViewLink || `https://docs.google.com/document/d/${f.id}/edit`,
  }));
}

/**
 * Creates an authoritative EA Sports FC 27 Tactical & Club Dossier in Google Docs.
 * Uses batchUpdate to construct structured sections with clear headings and body text.
 */
export async function createFc27TacticalDoc(
  title: string,
  sections: DocSection[]
): Promise<{ documentId: string; title: string; webViewLink: string }> {
  const token = getValidToken();

  // 1. Create blank document
  const createRes = await fetch('https://docs.googleapis.com/v1/documents', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      title: title.startsWith('FC27_') ? title : `FC27_${title}`,
    }),
  });

  if (!createRes.ok) {
    const errText = await createRes.text();
    throw new Error(`Failed to create Google Doc (${createRes.status}): ${errText}`);
  }

  const docData = await createRes.json();
  const documentId = docData.documentId;

  // 2. Build formatted text requests for batchUpdate
  // Compile full text and compute character offsets for styling
  let fullText = `${title}\n\n`;
  fullText += `Generated by EA Sports FC 27 Strategic Engine (Xbox Series S Console Edition)\n`;
  fullText += `Timestamp: ${new Date().toUTCString()} (T=0 British Time Europe/London)\n`;
  fullText += `═══════════════════════════════════════════════════════════════════\n\n`;

  for (const s of sections) {
    fullText += `■ ${s.heading.toUpperCase()}\n`;
    fullText += `${s.body.trim()}\n\n`;
    fullText += `───────────────────────────────────────────────────────────────────\n\n`;
  }

  // Insert the complete text content
  const insertRequest = {
    insertText: {
      location: { index: 1 },
      text: fullText,
    },
  };

  const updateRes = await fetch(`https://docs.googleapis.com/v1/documents/${documentId}:batchUpdate`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      requests: [insertRequest],
    }),
  });

  if (!updateRes.ok) {
    console.warn('Text batchUpdate warning for Doc:', await updateRes.text());
  }

  return {
    documentId,
    title: docData.title || title,
    webViewLink: `https://docs.google.com/document/d/${documentId}/edit`,
  };
}

/**
 * Appends a tactical note or live market intelligence update to an existing Google Doc.
 */
export async function appendNoteToGoogleDoc(
  documentId: string,
  noteHeading: string,
  noteBody: string
): Promise<void> {
  const token = getValidToken();

  // Fetch document to get the end index
  const docRes = await fetch(`https://docs.googleapis.com/v1/documents/${documentId}`, {
    headers: { Authorization: `Bearer ${token}` },
  });

  if (!docRes.ok) {
    throw new Error(`Failed to fetch Google Doc for append (${docRes.status})`);
  }

  const docData = await docRes.json();
  const bodyContent = docData.body?.content || [];
  const lastElement = bodyContent[bodyContent.length - 1];
  const endIndex = Math.max(1, (lastElement?.endIndex || 2) - 1);

  const appendText = `\n\n■ [UPDATE ${new Date().toLocaleTimeString('en-GB')}] ${noteHeading}\n${noteBody}\n`;

  const updateRes = await fetch(`https://docs.googleapis.com/v1/documents/${documentId}:batchUpdate`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      requests: [
        {
          insertText: {
            location: { index: endIndex },
            text: appendText,
          },
        },
      ],
    }),
  });

  if (!updateRes.ok) {
    const errText = await updateRes.text();
    throw new Error(`Failed to append note to Google Doc: ${errText}`);
  }
}

