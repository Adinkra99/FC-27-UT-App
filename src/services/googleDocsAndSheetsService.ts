// Helper to ensure authenticated token
function getValidToken(): string {
  const token = getAccessToken();
  if (!token) {
    throw new Error('GOOGLE_WORKSPACE_TOKEN_REQUIRED: Please sign in with Google to use Docs and Sheets.');
  }
  return token;
}

